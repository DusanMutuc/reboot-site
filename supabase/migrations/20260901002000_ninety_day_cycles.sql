begin;

create table public.ninety_day_cycles (
  id bigint generated by default as identity primary key,
  name text not null check (length(btrim(name)) between 1 and 120),
  starts_on date not null,
  ends_on date not null,
  timezone text not null default 'America/Edmonton'
    check (length(btrim(timezone)) between 1 and 80),
  status text not null default 'draft'
    check (status in ('draft', 'active', 'completed')),
  active_system_node_id bigint references public.content_nodes(id) on delete set null,
  created_by uuid references public.profiles(id) on delete set null,
  updated_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_on = starts_on + 89)
);

create unique index ninety_day_cycles_one_active_idx
  on public.ninety_day_cycles ((true))
  where status = 'active';

create table public.ninety_day_cycle_systems (
  cycle_id bigint not null references public.ninety_day_cycles(id) on delete cascade,
  node_id bigint not null references public.content_nodes(id) on delete restrict,
  position smallint not null check (position between 1 and 8),
  created_at timestamptz not null default now(),
  primary key (cycle_id, node_id),
  unique (cycle_id, position)
);

alter table public.ninety_day_cycles
  add constraint ninety_day_cycles_active_system_in_cycle_fk
  foreign key (id, active_system_node_id)
  references public.ninety_day_cycle_systems(cycle_id, node_id)
  deferrable initially deferred;

create table public.ninety_day_cycle_users (
  cycle_id bigint not null references public.ninety_day_cycles(id) on delete restrict,
  user_id uuid not null references public.profiles(id) on delete cascade,
  enrolled_at timestamptz not null default now(),
  ended_at timestamptz,
  outcome text check (outcome is null or outcome in ('promoted', 'removed', 'transferred')),
  primary key (cycle_id, user_id),
  check ((ended_at is null and outcome is null) or (ended_at is not null and outcome is not null))
);

create unique index ninety_day_cycle_users_one_open_enrollment_idx
  on public.ninety_day_cycle_users(user_id)
  where ended_at is null;

create table public.ninety_day_cycle_meetings (
  id bigint generated by default as identity primary key,
  cycle_id bigint not null references public.ninety_day_cycles(id) on delete cascade,
  title text not null default 'Weekly group call'
    check (length(btrim(title)) between 1 and 160),
  starts_at timestamptz not null,
  ends_at timestamptz,
  join_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (cycle_id, starts_at),
  check (ends_at is null or ends_at > starts_at),
  check (join_url is null or join_url ~ '^https?://')
);

create or replace function public.validate_ninety_day_system()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
begin
  if not exists (
    select 1
    from public.content_nodes node
    where node.id = new.node_id
      and node.state = 'published'
      and node.slug is not null
      and node.node_type in ('lesson', 'chapter', 'playlist')
  ) then
    raise exception '90-day systems must be published, linked learning nodes'
      using errcode = '23514';
  end if;

  return new;
end;
$$;

create trigger ninety_day_cycle_systems_validate
before insert or update of node_id on public.ninety_day_cycle_systems
for each row execute function public.validate_ninety_day_system();

create or replace function public.validate_ninety_day_cycle_activation()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
  system_count integer;
begin
  new.updated_at := now();

  if new.status = 'active' then
    select count(*) into system_count
    from public.ninety_day_cycle_systems
    where cycle_id = new.id;

    if system_count <> 8 then
      raise exception 'An active 90-day cycle must have exactly eight systems'
        using errcode = '23514';
    end if;

    if new.active_system_node_id is null then
      raise exception 'An active 90-day cycle must have a current system'
        using errcode = '23514';
    end if;
  end if;

  return new;
end;
$$;

create trigger ninety_day_cycles_validate_activation
before insert or update
on public.ninety_day_cycles
for each row execute function public.validate_ninety_day_cycle_activation();

