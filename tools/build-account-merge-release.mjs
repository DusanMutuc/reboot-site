import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
export const migrationPath = 'supabase/migrations/20261008010000_archive_merged_accounts.sql';
export const releasePath = 'sql/2026-10-08_merged_accounts_release.sql';

export function renderAccountMergeRelease(rawMigration) {
  const migration = rawMigration.replaceAll('\r\n', '\n');
  if ((migration.match(/^begin;$/gm) ?? []).length !== 1
      || (migration.match(/^commit;$/gm) ?? []).length !== 1
      || !/\ncommit;\s*$/.test(migration)) {
    throw new Error('Canonical migration must contain one outer BEGIN/COMMIT pair.');
  }
  const body = migration.replace(/^begin;\n/m, '').replace(/\ncommit;\s*$/, '\n').trimEnd();
  const delimiter = '$migration_20261008010000$';
  if (migration.includes(delimiter)) throw new Error('Migration history dollar-quote collision.');
  return `-- Merged member accounts release, 2026-10-08.
-- Generated by node tools/build-account-merge-release.mjs. Run the ENTIRE file
-- in the intended Supabase project's SQL Editor using postgres. Preserve the
-- existing functions, policies, RLS flags and authenticator settings first.
-- Installs only the new archive migration; does not merge any member accounts.
-- All DDL, verification and exact migration history registration are atomic.
-- A registered/partial release is rejected. Do not delete history to rerun it.
-- Source SHA-256 (LF): ${createHash('sha256').update(migration).digest('hex')}

begin;
set local lock_timeout = '10s';
set local statement_timeout = '120s';
set local check_function_bodies = on;
do $release_preflight$
declare required text;
begin
  if current_user not in ('postgres','supabase_admin') then
    raise exception 'Run the merged-account release using postgres in the intended project.';
  end if;
  perform pg_advisory_xact_lock(hashtextextended('account-merge-release-2026-10-08',0));
  if to_regclass('supabase_migrations.schema_migrations') is null then
    raise exception 'Migration history is missing.';
  end if;
  lock table supabase_migrations.schema_migrations in share row exclusive mode;
  if exists(select 1 from supabase_migrations.schema_migrations where version='20261008010000') then
    raise exception 'Merged-account release 20261008010000 is already registered.';
  end if;
  if not exists(select 1 from supabase_migrations.schema_migrations where version='20261008000000') then
    raise exception 'The complete account-transfer release must be installed and registered first.';
  end if;
  foreach required in array array['public.transfer_user_data_admin_v2(uuid,uuid,jsonb)',
    'public.get_account_transfer_result_v2(uuid,uuid,jsonb)', 'public.get_current_member_ids()',
    'public.get_all_users(integer)', 'public.get_my_users(bigint)', 'public.get_my_users_with_status()',
    'public.apply_user_attention_auto(uuid)'] loop
    if to_regprocedure(required) is null then raise exception 'Missing prerequisite function %.',required; end if;
  end loop;
  if to_regclass('public.account_merges') is not null
    or to_regclass('public.account_merge_access_settings') is not null
    or to_regprocedure('public.transfer_user_data_admin_v3(uuid,uuid,jsonb)') is not null
    or exists(select 1 from information_schema.columns where table_schema='public'
      and table_name='profiles' and column_name in ('merged_at','merged_into_user_id')) then
    raise exception 'Unexpected partial merged-account release; inspect before proceeding.';
  end if;
end;
$release_preflight$;

${body}

do $release_postconditions$
declare entrypoint text; browser_role text; relation record;
begin
  foreach entrypoint in array array['public.transfer_user_data_admin_v3(uuid,uuid,jsonb)',
    'public.get_account_transfer_result_v3(uuid,uuid,jsonb)'] loop
    if not exists(select 1 from pg_proc where oid=to_regprocedure(entrypoint) and prosecdef)
      or not has_function_privilege('service_role',entrypoint,'EXECUTE')
      or has_function_privilege('anon',entrypoint,'EXECUTE')
      or has_function_privilege('authenticated',entrypoint,'EXECUTE') then
      raise exception 'Release verification failed: % must be service-only SECURITY DEFINER.',entrypoint;
    end if;
  end loop;
  foreach browser_role in array array['anon','authenticated'] loop
    if has_table_privilege(browser_role,'public.account_merges','SELECT,INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER')
      or has_table_privilege(browser_role,'public.account_merge_access_settings','SELECT,INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER') then
      raise exception 'Release verification failed: private archive tables accessible to %.',browser_role;
    end if;
  end loop;
  if has_table_privilege('service_role','public.account_merges','INSERT,UPDATE,DELETE,TRUNCATE')
    or not has_table_privilege('service_role','public.account_merges','SELECT') then
    raise exception 'Release verification failed: archive ledger must be service-read-only.';
  end if;
  for relation in select c.oid,c.relname,n.nspname,c.relrowsecurity from pg_class c
    join pg_namespace n on n.oid=c.relnamespace where c.relkind in ('r','p')
      and (n.nspname='public' or (n.nspname='storage' and c.relname in ('objects','buckets'))) loop
    if not relation.relrowsecurity or not exists(select 1 from pg_policy where polrelid=relation.oid
        and polname='account_merge_subject_guard' and not polpermissive) then
      raise exception 'Release verification failed: archive access restriction missing on %.%.',relation.nspname,relation.relname;
    end if;
  end loop;
  if not exists(select 1 from pg_db_role_setting s cross join lateral unnest(s.setconfig) v
    where s.setrole=(select oid from pg_roles where rolname='authenticator')
      and s.setdatabase=(select oid from pg_database where datname=current_database())
      and v='pgrst.db_pre_request=public.account_merge_pre_request') then
    raise exception 'Release verification failed: API request guard is not installed.';
  end if;
  if not exists(select 1 from pg_trigger where tgrelid='public.profiles'::regclass
    and tgname='profiles_protect_account_merge' and not tgisinternal and tgenabled in ('O','A'))
    or not exists(select 1 from pg_trigger where tgrelid='public.account_merges'::regclass
      and tgname='account_merges_immutable' and not tgisinternal and tgenabled in ('O','A')) then
    raise exception 'Release verification failed: archive immutability guards are missing.';
  end if;
end;
$release_postconditions$;

insert into supabase_migrations.schema_migrations(version,name,statements)
values ('20261008010000','archive_merged_accounts',array[${delimiter}${migration}${delimiter}]::text[]);
commit;
select version,name from supabase_migrations.schema_migrations where version='20261008010000';
select 'Merged-account schema installed. Deploy the matching application before merging a member.' as release_status;
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(root, releasePath), renderAccountMergeRelease(readFileSync(path.join(root, migrationPath), 'utf8')));
  console.log(`Generated ${releasePath}`);
}
