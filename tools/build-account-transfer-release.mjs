export function renderAccountTransferRelease(rawMigration) {
  const migration = rawMigration.replaceAll('\r\n', '\n');
  const digest = createHash('sha256').update(migration).digest('hex');
  if ((migration.match(/^begin;$/gm) ?? []).length !== 1
    || (migration.match(/^commit;$/gm) ?? []).length !== 1
    || !/\ncommit;\s*$/.test(migration)) {
    throw new Error('Canonical migration must contain one outer BEGIN/COMMIT pair.');
  }
  const body = migration.replace(/^begin;\n/m, '').replace(/\ncommit;\s*$/, '\n').trimEnd();
  const delimiter = '$migration_20261008000000$';
  if (migration.includes(delimiter)) throw new Error('Migration history dollar-quote collision.');
  return `-- Member account transfer production release, 2026-10-08.
-- Generated by: node tools/build-account-transfer-release.mjs
-- Paste this ENTIRE file into the intended live project's Supabase SQL Editor
-- using the postgres role. Run once, without selecting only part of the script.
-- Confirm the project and retain the original transfer functions/ACLs first.
-- This applies only the new account-transfer migration. It does not run a
-- transfer, replay older migrations, or change any member history.
-- The schema changes, verification and migration-history entry are atomic.
-- Registered or partial releases fail before changes: inspect, do not rerun or
-- delete migration history. If an error leaves an aborted transaction open,
-- run ROLLBACK; before investigating. A timeout commits no release changes.
-- Source SHA-256 (LF): ${digest}

begin;
set local lock_timeout = '10s';
set local statement_timeout = '120s';
set local check_function_bodies = on;

do $release_preflight$
declare
  _name text;
  _column record;
begin
  if current_user not in ('postgres', 'supabase_admin') then
    raise exception 'Run this release through the intended project SQL Editor using the postgres role.';
  end if;
  perform pg_advisory_xact_lock(hashtextextended('account-transfer-release-2026-10-08',0));
  if to_regclass('supabase_migrations.schema_migrations') is null then
    raise exception 'Migration history is missing. Confirm the project and initialize normal Supabase migration history first.';
  end if;
  if (select count(*) from information_schema.columns
      where table_schema='supabase_migrations' and table_name='schema_migrations'
        and ((column_name in ('version','name') and udt_name='text')
          or (column_name='statements' and udt_name='_text'))) <> 3 then
    raise exception 'Unexpected migration history schema: expected version text, name text, statements text[].';
  end if;
  lock table supabase_migrations.schema_migrations in share row exclusive mode;
  if exists(select 1 from supabase_migrations.schema_migrations where version='20261008000000') then
    raise exception 'Account-transfer release 20261008000000 is already registered. Do not rerun; inspect the recorded release and deployed application.';
  end if;
  foreach _name in array array['anon','authenticated','service_role'] loop
    if not exists(select 1 from pg_roles where rolname=_name) then
      raise exception 'Required Supabase role % is missing. Confirm the selected project.',_name;
    end if;
  end loop;
  foreach _name in array ${sqlArray(relations)} loop
    if to_regclass(_name) is null then
      raise exception 'Missing prerequisite relation %. Apply/verify earlier Business Review, membership and implementation releases first.',_name;
    end if;
  end loop;
  if to_regtype('public.share_domain') is null then
    raise exception 'Missing prerequisite type public.share_domain.';
  end if;
  foreach _name in array ${sqlArray(prerequisites)} loop
    if to_regprocedure(_name) is null then
      raise exception 'Missing prerequisite function %. Verify earlier releases; this script does not apply them.',_name;
    end if;
  end loop;
  for _column in select * from (values
    ${sessionColumns.map(([name, type]) => `('${name}','${type}')`).join(',\n    ')}
  ) as required(column_name,udt_name) loop
    if not exists(select 1 from information_schema.columns actual
      where actual.table_schema='public' and actual.table_name='implementation_meeting_sessions'
        and actual.column_name=_column.column_name and actual.udt_name=_column.udt_name) then
      raise exception 'Missing or incompatible implementation session column % (%). Verify the coaching-history and next-meeting-booking releases.',_column.column_name,_column.udt_name;
    end if;
  end loop;
  foreach _name in array array[
    'public.transfer_user_data_admin_v2(uuid,uuid,jsonb)',
    'public.get_account_transfer_result_v2(uuid,uuid,jsonb)',
    'public.restore_account_transfer_smart_doc_metadata()'
  ] loop
    if to_regprocedure(_name) is not null then
      raise exception 'Unexpected existing release function %. This may be a partial/manual release; inspect before proceeding.',_name;
    end if;
  end loop;
  if to_regclass('public.user_merge_log_applied_request_id_idx') is not null
    or exists(select 1 from pg_trigger where tgname='zzz_account_transfer_metadata'
      and tgrelid in ('public.smart_doc_responses'::regclass,'public.smart_doc_response_values'::regclass)) then
    raise exception 'Existing account-transfer release index/trigger without migration history. Inspect this partial/manual release instead of rerunning.';
  end if;
end;
$release_preflight$;

-- Canonical migration body; only its outer BEGIN/COMMIT are omitted here.
${body}

do $release_postconditions$
declare
  _name text;
  _role text;
  _function oid;
begin
  foreach _name in array ${sqlArray(entrypoints)} loop
    _function := to_regprocedure(_name);
    if _function is null or not exists(select 1 from pg_proc where oid=_function and prosecdef) then
      raise exception 'Release verification failed: missing SECURITY DEFINER entry point %.',_name;
    end if;
    if not has_function_privilege('service_role',_function,'EXECUTE')
      or has_function_privilege('anon',_function,'EXECUTE')
      or has_function_privilege('authenticated',_function,'EXECUTE') then
      raise exception 'Release verification failed: entry point % is not service-role-only.',_name;
    end if;
  end loop;
  if not exists(select 1 from pg_class where oid='public.user_merge_log'::regclass and relrowsecurity) then
    raise exception 'Release verification failed: merge audit RLS is disabled.';
  end if;
  foreach _role in array array['anon','authenticated'] loop
    if has_table_privilege(_role,'public.user_merge_log','SELECT,INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER')
      or has_sequence_privilege(_role,'public.user_merge_log_id_seq','USAGE,SELECT,UPDATE') then
      raise exception 'Release verification failed: browser role % still has merge audit privileges.',_role;
    end if;
  end loop;
  if not exists(select 1 from pg_index
    where indexrelid='public.user_merge_log_applied_request_id_idx'::regclass
      and indrelid='public.user_merge_log'::regclass and indisunique and indisvalid) then
    raise exception 'Release verification failed: request replay index is missing or invalid.';
  end if;
  foreach _name in array array['public.smart_doc_responses','public.smart_doc_response_values'] loop
    if not exists(select 1 from pg_trigger where tgrelid=_name::regclass
      and tgname='zzz_account_transfer_metadata' and not tgisinternal
      and tgenabled in ('O','A') and tgtype=23
      and tgfoid='public.restore_account_transfer_smart_doc_metadata()'::regprocedure) then
      raise exception 'Release verification failed: metadata preservation trigger is missing or incompatible on %.',_name;
    end if;
  end loop;
end;
$release_postconditions$;

-- Store the exact canonical SQL (including its own transaction wrapper), as
-- normal Supabase migration history, only after all postconditions succeed.
insert into supabase_migrations.schema_migrations(version,name,statements)
values ('20261008000000','complete_account_transfers',array[${delimiter}${migration}${delimiter}]::text[]);

commit;

-- Read-only confirmation. This does not call any account-transfer function.
select version,name from supabase_migrations.schema_migrations where version='20261008000000';
select 'Account-transfer database update installed; deploy the matching application and preview the intended member pair before applying a transfer.' as release_status;
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(root, releasePath), renderAccountTransferRelease(readFileSync(path.join(root, migrationPath), 'utf8')));
  console.log(`Generated ${releasePath}`);
}
