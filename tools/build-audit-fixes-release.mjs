import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

export const auditMigrations = [
  '20261008019000_secure_onboarding',
  '20261008020000_content_access_and_progress',
  '20261008021000_smartdoc_submission_integrity',
  '20261008022000_atomic_partnership_management',
];
const root = fileURLToPath(new URL('../', import.meta.url));
export function renderAuditRelease(sources) {
  const parts = auditMigrations.map((name) => {
    const sql = sources[name].replaceAll('\r\n', '\n');
    if ((sql.match(/^begin;$/gm) ?? []).length !== 1 || (sql.match(/^commit;$/gm) ?? []).length !== 1)
      throw new Error(`Expected one outer transaction in ${name}`);
    const body = sql.replace(/^begin;\n/m, '').replace(/^commit;\s*$/m, '').trim();
    const [version, ...description] = name.split('_');
    const delimiter = `$migration_${version}$`;
    if (sql.includes(delimiter)) throw new Error('Migration dollar quote collision');
    return `-- ${name}; SHA-256(LF): ${createHash('sha256').update(sql).digest('hex')}\n${body}\n\n` +
      `insert into supabase_migrations.schema_migrations(version,name,statements) values ('${version}','${description.join('_')}',array[${delimiter}${sql}${delimiter}]::text[]);`;
  });
  return `-- Generated by tools/build-audit-fixes-release.mjs. Back up functions, policies,
-- grants and authenticator settings before running the ENTIRE file as postgres.
-- DDL, derived claims and exact migration history registration are atomic.
-- This file does not change member passwords or send emails.
begin;
set local lock_timeout='10s';
set local statement_timeout='120s';
set local check_function_bodies=on;
do $preflight$
begin
  if current_user not in ('postgres','supabase_admin') then raise exception 'Use postgres for this release'; end if;
  perform pg_advisory_xact_lock(hashtextextended('audit-fixes-2026-10-08',0));
  lock table supabase_migrations.schema_migrations in share row exclusive mode;
  if not exists(select 1 from supabase_migrations.schema_migrations where version='20261008010000') then
    raise exception 'Archive migration must be registered first'; end if;
  if exists(select 1 from supabase_migrations.schema_migrations where version in (${auditMigrations.map(n => `'${n.slice(0,14)}'`).join(',')})) then
    raise exception 'One or more audit migrations are already registered; inspect before proceeding'; end if;
end $preflight$;

${parts.join('\n\n')}

do $verify$
declare r record; entrypoint text;
begin
  if has_function_privilege('authenticated','public.save_partnership_admin(uuid,jsonb)','EXECUTE')
    or has_function_privilege('anon','public.submit_smart_doc(bigint,uuid)','EXECUTE')
    or not has_function_privilege('service_role','public.save_partnership_admin(uuid,jsonb)','EXECUTE') then
    raise exception 'Audit release RPC privilege verification failed'; end if;
  foreach entrypoint in array array['public.set_node_state(bigint,text)',
    'public.set_course_order(bigint[])','public.enforce_strict_sequence(bigint,boolean)'] loop
    if has_function_privilege('anon',entrypoint,'EXECUTE')
      or has_function_privilege('authenticated',entrypoint,'EXECUTE')
      or not has_function_privilege('service_role',entrypoint,'EXECUTE') then
      raise exception 'Builder mutation must remain service-only: %',entrypoint; end if;
  end loop;
  for r in select schemaname,tablename from pg_policies where policyname='account_merge_subject_guard' loop
    if not exists(select 1 from pg_policies p where p.schemaname=r.schemaname and p.tablename=r.tablename
      and p.policyname='account_setup_subject_guard' and p.permissive='RESTRICTIVE') then
      raise exception 'Setup restriction missing on %.%',r.schemaname,r.tablename; end if;
  end loop;
  if not exists(select 1 from pg_db_role_setting s cross join lateral unnest(s.setconfig) v
    where s.setrole=(select oid from pg_roles where rolname='authenticator')
      and s.setdatabase=(select oid from pg_database where datname=current_database())
      and v='pgrst.db_pre_request=public.account_setup_pre_request') then
    raise exception 'Setup API guard is missing'; end if;
end $verify$;
commit;
select version,name from supabase_migrations.schema_migrations
where version in (${auditMigrations.map(n => `'${n.slice(0,14)}'`).join(',')}) order by version;
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const sources = Object.fromEntries(auditMigrations.map(name => [name, readFileSync(path.join(root,'supabase/migrations',name+'.sql'),'utf8')]));
  writeFileSync(path.join(root,'sql/2026-10-08_audit_fixes_release.sql'),renderAuditRelease(sources));
  console.log('Generated sql/2026-10-08_audit_fixes_release.sql');
}
